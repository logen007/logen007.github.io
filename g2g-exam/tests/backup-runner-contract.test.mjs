import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const base=new URL('../scripts/backup/',import.meta.url);
const read=name=>readFileSync(new URL(name,base),'utf8');
const backup=read('backup.sh');
const capture=read('capture.sh');
const runner=read('runner.sh');
const restore=read('restore.sh');
assert.ok(capture.indexOf('validate-deployment.mjs')<capture.indexOf('pg_dump --format'), 'Deployment must be validated before dump');
assert.match(capture,/media-final\.json/);
assert.match(capture,/verify-staging\.mjs/);
assert.match(backup,/capture\.mjs/);
assert.match(capture,/PGSERVICE=g2g_backup_capture PGSERVICEFILE="\$service_file" pg_dump/,'DB password is not a process argument');
assert.match(capture,/libpq-service\.mjs/,'The libpq service file carries the complete database URI');
assert.match(backup,/remote_hash/);
assert.match(backup,/age -r/);
assert.match(backup,/--exclude='\.\_\*'/,'Platform metadata must not enter verified backup payloads');
assert.match(runner,/flock -n/);
assert.match(runner,/prepare-rclone\.mjs/);
assert.match(restore,/age -d/);
assert.match(restore,/safe-extract\.py/);
assert.match(restore,/pg_restore --list/);
console.log('Backup runner integration contracts passed');
