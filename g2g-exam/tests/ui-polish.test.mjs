assert.match(html,/data-action="student-profile"[^>]+>Student<\/button>/);
assert.match(html,/class="confirmation-code"/);assert.doesNotMatch(html,/>Thông tin</);
assert.doesNotMatch(classesHtml({data}),/data-action="edit-class"/);
assert.match(classesHtml({data,classId:'c'}),/<h1>A1-01<\/h1>/);
html=trashAdminHtml({data,retentionDays:17});
assert.match(html,/Dữ liệu xóa sau 17 ngày/);assert.doesNotMatch(html,/>Câu hỏi</);
data.questions.push({id:'q',status:'trash',title:'Deleted'});
assert.match(trashAdminHtml({data}),/>Câu hỏi</);
html=teachersAdminHtml({data,user:teacher});
assert.match(html,/<th>Lần thi<\/th><th>Lớp<\/th>/);assert.doesNotMatch(html,/>Đặt làm Giáo viên</);
assert.match(examAdminHtml({data,user:teacher}),/class="nhan exam-provider" data-provider="TELC"/);
const section={id:'part',name:'Nghe 1',skill:'Nghe',skillKey:'listening',questionIds:['q'],instruction:'First prompt',additionalInstructions:[{id:'p2',text:'Second prompt',afterQuestion:1}],audioPolicy:{segmentRepeat:2}};
assert.match(partDisplayHtml({},section,false),/Lặp 1 lần/);
assert.match(partDisplayHtml({},{...section,audioFlow:{segmentRepeat:1}},false),/Không lặp/);
assert.match(partDisplayHtml({},{...section,displaySplit:true},true),/aria-pressed="true"[^>]*disabled/);
const state={exams:[],questions:[{id:'q',title:'Question',type:'single',choices:['A','B']}],attempts:[],auditLog:[]};
const exam=createExam(state,teacher,{title:'Layout',sections:[section]});
updateSection(state,teacher,exam.id,section.id,{displaySplit:true});
assert.equal(duplicateExam(state,teacher,exam.id).sections[0].displaySplit,true);
assert.equal(partUsesSplit({provider:'TELC',level:'B1'},{skill:'Viết',displaySplit:false}),false);
const storage=globalThis.sessionStorage;
globalThis.sessionStorage={getItem:()=>null};
html=examHtml({exam,sectionIndex:0,attempt:{answers:{}},questions:[{id:'q',title:'Question',type:'single',choices:['A','B']}],preview:true});
assert.ok(html.indexOf('Second prompt')<html.indexOf('<section class="to-thi"'),'All authored prompts belong to the left desktop column');
exam.sections[0].displaySplit=false;
assert.doesNotMatch(examHtml({exam,sectionIndex:0,attempt:{answers:{}},questions:[],preview:true}),/exam-stimulus-group/);
if(storage===undefined)delete globalThis.sessionStorage;else globalThis.sessionStorage=storage;
console.log('UI polish: badges, read receipts, compact rosters, retention and persisted part layout passed.');
