assert.doesNotMatch(html,/>Xem kết quả<\/button>/);
attempt.viewedPublication=attempt.publishedAt;
assert.doesNotMatch(studentResultsHtml({data,user}),/>Mới</);
attempt.publishedAt='2026-10-16';
