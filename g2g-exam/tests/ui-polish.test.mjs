import assert from 'node:assert/strict';
import {studentResultsHtml} from '../src/views/student-results.js';
import {studentRosterHtml,classesHtml} from '../src/views/classes.js';
import {trashAdminHtml,teachersAdminHtml,examAdminHtml} from '../src/views/admin.js';
import {partDisplayHtml,partUsesSplit} from '../src/ui/part-display.js';
import {examHtml} from '../src/views/student.js';
import {createExam,updateSection,duplicateExam} from '../src/domain/exams.js';

const user={id:'s',role:'student',name:'Student',email:'s@test.invalid',confirmationCode:'ABCDE'};
const teacher={id:'t',role:'master'};
const attempt={id:'a',studentId:'s',examId:'e',status:'published',publishedAt:'2026-10-15',attemptNo:2};
const data={users:[user],classes:[{id:'c',code:'A1-01'}],exams:[{id:'e',title:'Exam',provider:'TELC',level:'B1',status:'published'}],questions:[],attempts:[attempt]};
let html=studentResultsHtml({data,user});
assert.match(html,/<a class="student-result-row"[^>]+data-action="student-attempt-detail"/);
