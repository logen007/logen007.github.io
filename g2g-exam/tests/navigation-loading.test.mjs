import assert from 'node:assert/strict';
import {createNavigationLoading} from '../src/ui/navigation-loading.js';
const nodes=[];
const doc={createElement:()=>({attrs:{},setAttribute(k,v){this.attrs[k]=v;},remove(){nodes.splice(nodes.indexOf(this),1);}}),body:{append:node=>nodes.push(node)}};
const loading=createNavigationLoading(doc);
let finish;
const first=loading(()=>new Promise(resolve=>{finish=resolve;}));
assert.equal(nodes.length,1);
assert.equal(nodes[0].attrs.role,'progressbar');
assert.equal(nodes[0].attrs['aria-valuenow'],undefined);
await assert.rejects(loading(async()=>{throw Error('Network failure');}),/Network failure/);
assert.equal(nodes.length,1,'Overlapping failure must not hide another request');
finish(true);
assert.equal(await first,true);
assert.equal(nodes.length,0);
await assert.rejects(loading(()=>{throw Error('Synchronous failure');}));
assert.equal(nodes.length,0);
assert.equal(await loading(()=>42),42);
assert.equal(nodes.length,0);
console.log('Navigation loading cleanup, overlap and error tests passed.');
