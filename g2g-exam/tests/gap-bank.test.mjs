import assert from 'node:assert/strict';
import {seedState} from '../src/seed.js';
import {telcFixture} from './telc-b1-fixture.mjs';
import {splitGapBank,buildGapBank,distractorLines,shuffledGapSnapshot} from '../src/domain/gap-bank.js';
import {examQuestionNumbers} from '../src/domain/question-numbering.js';
import {gapAuthorText} from '../src/domain/inline-gaps.js';
import {inlineGapBuilder,saveInlineGapDraft,bindGapPositions} from '../src/part-templates/default/inline-gap-builder.js';
const state=structuredClone(seedState),teacher=state.users.find(u=>u.role==='teacher');
const {exam,rows}=telcFixture(state,teacher),section=exam.sections[4];
const numbers=examQuestionNumbers(exam,state.questions),original=splitGapBank(section,rows(section));
assert.equal(original.distractors.length,2);
const fields={'[data-gap-text]':{value:gapAuthorText(section,rows(section),numbers)},'[data-gap-distractors]':{value:original.distractors.join('\n')+'\n\n Extra 1\r\n Extra 2\n Extra 3\n'}};
rows(section).forEach((q,i)=>fields[`[data-gap-correct-text="${i}"]`]={value:original.answers[i]});
const root={querySelector:key=>fields[key]||null};
saveInlineGapDraft(root,state,teacher,exam,section);
assert.deepEqual(splitGapBank(section,rows(section)).answers,original.answers);
assert.equal(splitGapBank(section,rows(section)).distractors.length,5);
assert.equal(section.gapOptions.length,15);
const saved=JSON.stringify({exam,questions:state.questions});
const snapshot=shuffledGapSnapshot(exam,state.questions,()=>0);
const shuffled=snapshot.sections[4],questions=shuffled.questionIds.map(id=>snapshot.questionSnapshot.find(q=>q.id===id));
assert.notDeepEqual(shuffled.gapOptions,section.gapOptions);
assert.deepEqual(questions.map(q=>shuffled.gapOptions[q.correctAnswer]),original.answers);
assert.equal(JSON.stringify({exam,questions:state.questions}),saved,'Snapshot never mutates the source');
assert.deepEqual(JSON.parse(JSON.stringify(snapshot)),snapshot,'Reload keeps the saved order and keys');
assert.deepEqual(shuffledGapSnapshot(exam,state.questions,'preview'),shuffledGapSnapshot(exam,state.questions,'preview'));
assert.deepEqual(snapshot.sections[3].gapOptions,exam.sections[3].gapOptions,'Per-question choices unchanged');
assert.deepEqual(distractorLines(' A\n\n B\r\n'),['A','B']);
assert.throws(()=>buildGapBank(['A'],'A'),/trùng/);
assert.throws(()=>buildGapBank(['A'],Array.from({length:25},(_,i)=>'D'+i).join('\n')),/25/);
fields['[data-gap-text]'].value='{31} {33}';
saveInlineGapDraft(root,state,teacher,exam,section);
assert.deepEqual(section.gapPassage.filter(p=>typeof p==='object').map(p=>p.gap),[0,2]);
assert.deepEqual(splitGapBank(section,rows(section)).answers,original.answers,'Hidden draft rows retain their answers');
const html=inlineGapBuilder(section,rows(section),false,numbers);
assert.match(html,/data-gap-correct-text="0"/);assert.match(html,/data-gap-distractors/);
assert.doesNotMatch(html,/data-gap-answer=|data-gap-options-count|data-gap-resize/);
const groups=Array.from({length:10},(_,i)=>({dataset:{gapPosition:String(i)},hidden:false}));
const field={value:'{31} {33}',dataset:{gapNumbers:Array.from({length:10},(_,i)=>31+i).join(',')},addEventListener(){}};
bindGapPositions({querySelector:key=>key==='[data-gap-text]'?field:null,querySelectorAll:key=>key==='[data-gap-position]'?groups:[]},section);
assert.deepEqual(groups.map((g,i)=>!g.hidden?i:null).filter(i=>i!==null),[0,2]);
console.log('Gap bank: direct answers, distractor lines, sparse drafts, stable shuffle and key remapping passed.');
