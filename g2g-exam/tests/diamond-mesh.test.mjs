import assert from 'node:assert/strict';
import {diamondFrame,animateDiamond} from '../src/ui/diamond-mesh.js';
import {starFrame,animateStar} from '../src/ui/star-mesh.js';
const width=frame=>{
  const x=frame.flatMap(face=>face.points.split(' ').map(pair=>Number(pair.split(',')[0])));
  return Math.max(...x)-Math.min(...x);
};
assert.equal(diamondFrame().length,8);
assert.equal(new Set(diamondFrame().map(face=>face.id)).size,8);
assert.ok(width(diamondFrame(90))>35,'Side-on diamond retains real depth instead of collapsing into a flat line');
assert.ok(width(diamondFrame(90))<width(diamondFrame(0)));
assert.ok(diamondFrame(45).every((face,i,all)=>!i||all[i-1].depth<=face.depth),'Painter order follows visible face depth');
assert.notEqual(diamondFrame(45).find(face=>face.id===0).fill,diamondFrame(0).find(face=>face.id===0).fill,'A front face changes illumination with its angle');
const saved={requestAnimationFrame:globalThis.requestAnimationFrame,cancelAnimationFrame:globalThis.cancelAnimationFrame,document:globalThis.document};
let queue=[],id=0;
globalThis.requestAnimationFrame=callback=>{queue.push({id:++id,callback});return id;};
globalThis.cancelAnimationFrame=number=>{queue=queue.filter(item=>item.id!==number);};
globalThis.document={hidden:false};
const makePolygons=frame=>frame.map(face=>({dataset:{meshFace:String(face.id)},attributes:{points:face.points,fill:face.fill,'fill-opacity':face.opacity,'stroke-opacity':face.opacity*.55},setAttribute(key,value){this.attributes[key]=value;}}));
const polygons=makePolygons(diamondFrame());
const mesh={isConnected:true,querySelectorAll:()=>polygons,append(){}};
const initial=JSON.stringify(polygons.map(p=>p.attributes));
const run=time=>queue.shift().callback(time);
const rotation=animateDiamond(mesh);
run(0);run(375);
assert.notEqual(JSON.stringify(polygons.map(p=>p.attributes)),initial,'Points and lighting actually change during rotation');
globalThis.document.hidden=true;run(500);
assert.equal(JSON.stringify(polygons.map(p=>p.attributes)),initial,'Hidden-tab cancellation restores the final geometry');
assert.equal(queue.length,0);
assert.equal(starFrame().length,48);
assert.ok(width(starFrame(90))>25,'Extruded star has a visible thickness from its side');
assert.ok(starFrame(32).some(face=>face.id%4>=2&&face.opacity===1),'Tilting reveals star side faces');
assert.ok(starFrame().some(face=>face.opacity===0),'Hidden back faces do not show through');
const starPolygons=makePolygons(starFrame());
const starMesh={isConnected:true,querySelectorAll:()=>starPolygons,append(){}};
const starInitial=JSON.stringify(starPolygons.map(p=>p.attributes));
globalThis.document.hidden=false;
animateStar(starMesh);run(0);run(400);
assert.notEqual(JSON.stringify(starPolygons.map(p=>p.attributes)),starInitial,'Star geometry and lighting change with its tilt');
run(1200);run(1600);
assert.equal(JSON.stringify(starPolygons.map(p=>p.attributes)),starInitial,'Star settles into its original pose');
assert.equal(queue.length,0);
rotation.cancel();
globalThis.document.hidden=false;
animateDiamond(mesh);run(0);run(1500);
assert.equal(JSON.stringify(polygons.map(p=>p.attributes)),initial,'A complete turn returns exactly to the original mesh');
assert.equal(queue.length,0);
Object.assign(globalThis,saved);
console.log('Solid badge meshes: visible thickness, side faces, perspective, lighting, hidden-face culling, final restore and hidden-tab stop passed.');
