import assert from 'node:assert/strict';
import {readDashboardCache,writeDashboardCache,clearDashboardCache,patchDashboard} from '../src/ui/dashboard-cache.js';
import {setInfrastructureOwner,readCachedInfrastructure,refreshInfrastructure,clearInfrastructureCache} from '../src/settings/api.js';
import {ApiRepository} from '../src/repositories/api.js';
import {needsStateLoad} from '../src/repositories/state-scope.js';
import {dashboardHtml} from '../src/views/dashboard.js';
const saved={sessionStorage:globalThis.sessionStorage,fetch:globalThis.fetch};
const rows=new Map();
globalThis.sessionStorage={getItem:key=>rows.get(key),setItem:(key,value)=>rows.set(key,value),removeItem:key=>rows.delete(key)};
try{
  writeDashboardCache('one',{users:[{id:'u',role:'student',email:'private'}],exams:[],attempts:[{id:'a',answers:{secret:'answer'}}]});
  assert.equal(readDashboardCache('one').value.users[0].email,undefined);
  assert.equal(readDashboardCache('one').value.attempts[0].answers,undefined);
  assert.equal(readDashboardCache('two'),null);
  writeDashboardCache('one',{scope:'catalog',users:[],exams:[],attempts:[]});
  assert.equal(readDashboardCache('one').value.attempts.length,1,'Catalog must not erase cached attempt statistics');
  assert.equal(needsStateLoad('summary','catalog'),true,'Dashboard entry loads summary without waiting for polling');
  assert.equal(needsStateLoad('summary','summary'),false);
  assert.equal(needsStateLoad('summary',undefined),false,'Full state already satisfies dashboard');
  assert.equal(needsStateLoad('full','summary'),true);
  assert.equal(needsStateLoad('catalog','summary'),true);
  const cached={users:[{id:'s',role:'student',name:'Active student'}],exams:[{id:'e',title:'Exam',sections:[{name:'Viết 2',questionIds:['q']}]}],attempts:[{id:'a',examId:'e',studentId:'s',status:'published',aiWritingAccuracy:{q:{questionId:'q',accurate:true}}}]};
  writeDashboardCache('one',cached);
  const html=dashboardHtml({data:readDashboardCache('one').value});
  assert.match(html,/Active student/);
  assert.match(html,/Độ chính xác AI/,'Accuracy must not wait for infrastructure');
  assert.match(html,/1\/1/);
  const startupCalls=[];
  globalThis.fetch=async url=>{startupCalls.push(url);return {ok:true,json:async()=>url.endsWith('/auth/me')?{user:{id:'one',role:'master'}}:{scope:'summary',...cached}};};
  const repository=new ApiRepository();repository.startPolling=()=>{};
  await repository.init();
  assert.deepEqual(startupCalls,['/api/auth/me'],'Authenticated cached dashboard starts before summary download');
  assert.equal(repository.state.scope,'catalog');
  assert.equal(repository.state.attempts.length,0,'Display cache is not mutable repository state');
  repository.setPollingScope('summary');
  await Promise.all([repository.reload(),repository.reload()]);
  assert.deepEqual(startupCalls,['/api/auth/me','/api/state-summary'],'One immediate deduplicated summary request');
  assert.equal(repository.state.attempts.length,1);
  clearDashboardCache();assert.equal(readDashboardCache('one'),null);
  startupCalls.length=0;
  await repository.init();
  assert.deepEqual(startupCalls,['/api/auth/me','/api/state-summary'],'Cold dashboard still loads authoritative state');
  let calls=0,resolve;
  globalThis.fetch=()=>{calls++;return new Promise(done=>resolve=()=>done({ok:true,json:async()=>({resources:{cpu:1}})}));};
  setInfrastructureOwner('one');
  const first=refreshInfrastructure({summaryOnly:false}),second=refreshInfrastructure({summaryOnly:false});
  assert.equal(calls,1);resolve();await Promise.all([first,second]);
  assert.equal(readCachedInfrastructure().resources.cpu,1);
  await refreshInfrastructure({summaryOnly:false});assert.equal(calls,1,'Fresh cache avoids a second reload request');
  setInfrastructureOwner('two');assert.equal(readCachedInfrastructure(),null);
  clearInfrastructureCache();setInfrastructureOwner('one');assert.equal(readCachedInfrastructure(),null);
  let writes=0;
  patchDashboard({isEqualNode:()=>true,replaceWith:()=>writes++},{});
  assert.equal(writes,0,'Unchanged dashboard nodes remain untouched');
  const text={nodeType:3,nodeName:'#text',nodeValue:'old',isEqualNode:()=>false};
  patchDashboard(text,{nodeType:3,nodeName:'#text',nodeValue:'new'});
  assert.equal(text.nodeValue,'new');
}finally{Object.assign(globalThis,saved);clearInfrastructureCache();}
console.log('Dashboard cache: owner isolation, private-field exclusion, logout, request deduplication, freshness and unchanged-node preservation passed.');
