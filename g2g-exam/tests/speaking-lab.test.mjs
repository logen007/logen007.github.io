import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {validateTrial,trialView,isPhone,clockText} from '../src/speaking/model.js';
import {trialDefaults,adminTrialHtml} from '../src/speaking/admin.js';
import {loginReturnPath} from '../server/src/auth-routing.js';
import {initialStateScope,viewStateScope} from '../src/repositories/state-scope.js';
const time=Date.now(),input={title:'Trial',scheduledAt:new Date(time+60000).toISOString(),emailA:'a@test.example',emailB:'b@test.example',stages:trialDefaults()};
assert.equal(validateTrial(input,time).stages.length,3);
assert.throws(()=>validateTrial({...input,emailB:input.emailA},time),/khác nhau/);
assert.throws(()=>validateTrial({...input,stages:[{...input.stages[0],seconds:-1}]},time),/thời lượng/);
assert.throws(()=>validateTrial({...input,stages:Array(4).fill({...input.stages[0],seconds:1000})},time),/30 phút/);
assert.equal(isPhone('Mozilla iPhone Safari'),true);assert.equal(isPhone('Android Mobile Chrome'),true);assert.equal(isPhone('Macintosh Chrome'),false);
assert.equal(clockText(65),'1:05');
const row={id:'trial',owner_id:'teacher',data:{...validateTrial(input,time),state:'waiting',members:[{id:'a',name:'A'},{id:'b',name:'B'}],ready:{},reviews:{a:'private review'},markers:[]}};
assert.throws(()=>trialView(row,{id:'other',role:'student'}),/không được xếp/);
assert.equal(trialView(row,{id:'a',role:'student'}).stage,null);
row.data.state='running';row.data.stageIndex=1;
const a=trialView(row,{id:'a',role:'student'}),b=trialView(row,{id:'b',role:'student'});
assert.equal(a.stage.prompt,input.stages[1].a);assert.equal(b.stage.prompt,input.stages[1].b);
assert.equal(a.stages,undefined);assert.equal(a.reviews,undefined);assert.ok(!JSON.stringify(a).includes(input.stages[1].b));
assert.equal(trialView(row,{id:'teacher',role:'teacher'}).stages.length,3);
assert.throws(()=>trialView(row,{id:'different-teacher',role:'teacher'}),/không được xếp/);
const link='/speaking-lab.html?session=12345678-1234-1234-1234-123456789abc';
assert.equal(loginReturnPath(link,'student'),link);assert.equal(loginReturnPath('//evil.test'+link,'student'),'/student');
assert.equal(initialStateScope({role:'master'},'https://g2g.test/adm?tab=speaking'),'catalog');assert.equal(viewStateScope('admin','speaking'),'catalog');
assert.match(adminTrialHtml(),/không ghi vào kết quả thi thật/);
const source=readFileSync(new URL('../src/speaking/phone.js',import.meta.url),'utf8');
assert.match(source,/acquirePreview/);assert.match(source,/consent:true/);assert.match(source,/document\.hidden/);
assert.match(source,/actions\?\.leave/);assert.match(source,/URL\.revokeObjectURL/);
console.log('Speaking trial: validation, private A/B prompts, teacher ownership, phone gate and safe login return passed.');
