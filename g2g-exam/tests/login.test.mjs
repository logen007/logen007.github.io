import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {loginHtml} from '../src/views/login.js';
import {bindLoginMotion} from '../src/ui/login-motion.js';
const api=loginHtml({mode:'api'}),local=loginHtml({mode:'local'});
assert.equal((api.match(/id="googleLogin"/g)||[]).length,1);
assert.match(api,/<button type="button"[^>]+id="googleLogin"/);
assert.match(api,/Tiếp tục với Google/);
assert.doesNotMatch(api,/demo-login|nhiều nhất|nhiều <strong>nhì/);
assert.equal((local.match(/demo-login/g)||[]).length,3);
for(const hook of ['id="landingTypes"','id="landingMetrics"','aria-live="polite"','data-action="toggle-color-mode"','data-no-tooltip','aria-labelledby="login-title"','href="/privacy.html"','href="/terms.html"'])assert.ok(api.includes(hook),hook);
assert.match(api,/Minh họa trải nghiệm luyện thi, không phải kết quả thực tế/);
assert.match(api,/Thi thử trước\.<br>Tự tin khi thi thật\./);
assert.doesNotMatch(api,/bước tiến mới|một hành trình|điều tiếp theo|landing-sheet/);
assert.match(api,/data-login-scene aria-hidden="true"/);
assert.match(api,/<svg class="landing-google-mark"[^>]+viewBox="0 0 48 48"/);
for(const color of ['#EA4335','#4285F4','#FBBC05','#34A853'])assert.ok(api.includes(color));
assert.match(api,/<button type="button"[^>]+data-login-replay/);
const caption={textContent:'Initial'},button={disabled:true,textContent:'Keep decorative children',querySelector:()=>caption};
const context={localOnly:false,pub:{auth:{googleLoginEnabled:true}},document:{getElementById:()=>button}};
const settings=readFileSync(new URL('../src/settings.js',import.meta.url),'utf8');
const applyLogin=vm.runInNewContext('('+settings.match(/function applyLogin\(\)\{[\s\S]*?\n\}/)[0]+')',context);
applyLogin();assert.equal(button.disabled,false);assert.equal(caption.textContent,'Tiếp tục với Google');
assert.equal(button.textContent,'Keep decorative children','Public settings keep the official Google logo mounted');
context.pub.auth.googleLoginEnabled=false;applyLogin();assert.equal(button.disabled,true);assert.equal(caption.textContent,'Đăng nhập Google đang tạm tắt');
context.localOnly=true;caption.textContent='Demo';applyLogin();assert.equal(caption.textContent,'Demo');
const css=readFileSync(new URL('../styles.css',import.meta.url),'utf8');
const motion=css.match(/@media\(prefers-reduced-motion:no-preference\) \{([\s\S]+?)\n\}/)?.[1];
assert.ok(motion);
assert.doesNotMatch(motion,/infinite|landing-cta|landing-login|landing-copy/,'Authentication is never delayed or moved by decorative motion');
assert.match(css,/@keyframes landing-screen/);
assert.match(css,/\.landing-replay \{ display:none; \}/);
assert.match(css,/\.landing \.landing-cta:focus-visible/);
assert.match(css,/\.landing-signin \{ order:1;/);
assert.match(css,/\.landing-visual \{ order:2;/);
assert.match(css,/\.landing-demo-screen \{[^}]*min-height:332px/,'The screen must grow with wrapped question text');
assert.doesNotMatch(css.match(/\.landing-demo-screen \{[^}]*\}/)?.[0]||'',/(?<!-)\bheight:/,'No fixed or percentage height can crop the illustration');
assert.ok(api.indexOf('id="googleLogin"')<api.indexOf('data-login-replay'),'Google remains before replay in keyboard order');
const animations=[{currentTime:2700,plays:0,play(){this.plays++;}},{currentTime:1800,plays:0,play(){this.plays++;}}];
const replay={hidden:false},scene={getAnimations(options){assert.deepEqual(options,{subtree:true});return animations;}};
const root={querySelector:selector=>selector==='[data-login-scene]'?scene:replay};
let reduce=false;
bindLoginMotion(root,{reducedMotion:()=>reduce});
assert.equal(replay.hidden,false);replay.onclick();
assert.ok(animations.every(a=>a.currentTime===0&&a.plays===1));
replay.onclick();assert.ok(animations.every(a=>a.plays===2),'Repeated replay restarts existing animations, no new timers');
reduce=true;replay.onclick();assert.ok(animations.every(a=>a.plays===2),'Recheck the live reduced-motion setting at every replay');
bindLoginMotion({querySelector:selector=>selector==='[data-login-scene]'?{}:replay});
assert.equal(replay.hidden,true);replay.onclick();
bindLoginMotion({querySelector:()=>null});
console.log('Login: Google branding/settings, static auth, finite scene, reduced motion, replay/fallback, mobile order and policy contracts passed.');
