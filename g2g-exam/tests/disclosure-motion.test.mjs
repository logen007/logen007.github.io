import assert from 'node:assert/strict';
import {bindDisclosureMotion} from '../src/ui/disclosure-motion.js';
let click;
bindDisclosureMotion({addEventListener(type,handler){assert.equal(type,'click');click=handler;}});
let animation,prevented=false;
const details={tagName:'DETAILS',open:false,style:{overflow:''},getBoundingClientRect(){return {height:this.open?300:40};},animate(frames,options){animation={frames,options,cancel(){this.oncancel?.();}};return animation;}};
const summary={parentElement:details};
const event=()=>({target:{closest(selector){return selector==='summary'?summary:null;}},preventDefault(){prevented=true;}});
click(event());
assert.equal(prevented,true);
assert.equal(details.open,true);
assert.deepEqual(animation.frames,[{height:'40px'},{height:'300px'}]);
animation.onfinish();
assert.equal(details.style.overflow,'');
click(event());
assert.deepEqual(animation.frames,[{height:'300px'},{height:'40px'}]);
assert.equal(details.open,true,'content remains present while sliding closed');
animation.onfinish();assert.equal(details.open,false);
click(event());const first=animation;click(event());const second=animation;
first.onfinish();assert.equal(details.open,true,'cancelled completion cannot override current transition');
second.onfinish();assert.equal(details.open,false);
globalThis.matchMedia=()=>({matches:true});prevented=false;click(event());
assert.equal(prevented,false,'reduced motion retains instant native behavior');
delete globalThis.matchMedia;
console.log('Disclosure motion tests passed.');
