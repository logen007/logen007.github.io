import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {bindImageSheetSync} from '../src/ui/image-sheet-sync.js';
const index=await fs.readFile(new URL('../server/src/index.js',import.meta.url),'utf8');
const server=await fs.readFile(new URL('../server/src/image-sheet.js',import.meta.url),'utf8');
assert.doesNotMatch(index,/startImageSheetSync/);
assert.doesNotMatch(server,/setTimeout|setInterval|startImageSheetSync/,'No background image synchronization');
let calls=0,finish,messages=[];
const button={disabled:false,textContent:'Đồng bộ ảnh',setAttribute(){},removeAttribute(){}};
const root={querySelectorAll:()=>[button]};
bindImageSheetSync(root,{repo:{syncImageSheet(){calls++;return new Promise(resolve=>{finish=resolve;});}},notify:m=>messages.push(m)});
assert.equal(calls,0,'Binding/opening page must not synchronize');
const pending=button.onclick();assert.equal(calls,1);assert.equal(button.disabled,true);
await button.onclick();assert.equal(calls,1,'Ignore duplicate clicks');
finish({added:2,skipped:3});await pending;
assert.equal(button.disabled,false);assert.equal(button.textContent,'Đồng bộ ảnh');assert.match(messages[0],/2 ảnh mới/);
bindImageSheetSync(root,{repo:{syncImageSheet:async()=>{throw Error('Synthetic failure');}},notify:m=>messages.push(m)});
await button.onclick();assert.equal(messages.at(-1),'Synthetic failure');assert.equal(button.disabled,false);
console.log('Manual image sync: no scheduler, no mount side effects, click only, duplicate prevention, feedback and failure recovery passed.');
